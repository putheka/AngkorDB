//! What the sidebar, data grid and autocomplete learn about a database.

use serde::Serialize;

#[derive(Debug, Clone, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct DatabaseInfo {
    pub name: String,
    /// The database this session is connected to.
    pub is_current: bool,
}

#[derive(Debug, Clone, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct SchemaInfo {
    pub name: String,
    pub owner: String,
    /// `pg_*` and `information_schema`.
    pub is_system: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub enum ObjectKind {
    Table,
    PartitionedTable,
    ForeignTable,
    View,
    MaterializedView,
    Sequence,
    Function,
    Procedure,
    EnumType,
}

impl ObjectKind {
    /// Parse the `kind` column of the `list_objects` query.
    pub fn from_sql(kind: &str) -> Option<Self> {
        Some(match kind {
            "table" => Self::Table,
            "partitionedTable" => Self::PartitionedTable,
            "foreignTable" => Self::ForeignTable,
            "view" => Self::View,
            "materializedView" => Self::MaterializedView,
            "sequence" => Self::Sequence,
            "function" => Self::Function,
            "procedure" => Self::Procedure,
            "enumType" => Self::EnumType,
            _ => return None,
        })
    }
}

/// One entry of the sidebar tree.
#[derive(Debug, Clone, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct DbObject {
    /// `pg_class` / `pg_proc` / `pg_type` OID. Overloaded functions share a name, not an OID.
    pub oid: u32,
    pub schema: String,
    pub name: String,
    pub kind: ObjectKind,
    /// From `pg_class.reltuples`: an estimate that is stale until the next ANALYZE.
    /// `None` for views, sequences, functions, and tables never analyzed.
    pub row_estimate: Option<f64>,
    /// Functions: `(arguments) → result type`.
    pub detail: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub enum ColumnIdentity {
    /// `GENERATED ALWAYS AS IDENTITY`
    Always,
    /// `GENERATED BY DEFAULT AS IDENTITY`
    ByDefault,
}

/// A column of this table that points at a column of another table.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct ForeignKeyRef {
    pub constraint: String,
    pub schema: String,
    pub table: String,
    pub column: String,
}

/// What the SQL editor needs to complete names: every table and view with its columns, and the
/// user-defined functions, across all non-system schemas (ANG-30).
#[derive(Debug, Clone, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct CompletionSchema {
    /// `current_schemas(false)`: the schemas whose objects can be named without a prefix.
    pub search_path: Vec<String>,
    pub tables: Vec<CompletionTable>,
    pub functions: Vec<CompletionFunction>,
}

#[derive(Debug, Clone, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct CompletionTable {
    pub schema: String,
    pub name: String,
    pub kind: ObjectKind,
    pub columns: Vec<CompletionColumn>,
}

#[derive(Debug, Clone, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct CompletionColumn {
    pub name: String,
    /// As Postgres prints it: `numeric(20,6)`.
    pub type_name: String,
}

#[derive(Debug, Clone, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct CompletionFunction {
    pub schema: String,
    pub name: String,
    /// `(p_name text DEFAULT 'world'::text) → text`
    pub signature: String,
}

/// A foreign key of another table that points at this one ("referenced by"). The two column
/// lists are in constraint order: `columns[i]` of `schema.table` references `referenced_columns[i]`
/// of the table asked about.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct IncomingForeignKey {
    pub constraint: String,
    pub schema: String,
    pub table: String,
    pub columns: Vec<String>,
    pub referenced_columns: Vec<String>,
}

#[derive(Debug, Clone, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct ColumnInfo {
    pub name: String,
    /// 1-based position in the table.
    pub position: u16,
    /// As Postgres prints it: `numeric(20,6)`, `character varying(100)`, `text[]`.
    pub type_name: String,
    /// The type without length or precision (`numeric`). Edits cast to this (ANG-8 D7).
    pub base_type: String,
    pub type_oid: u32,
    pub nullable: bool,
    /// The `DEFAULT` expression as SQL text, e.g. `now()`.
    pub default_value: Option<String>,
    pub identity: Option<ColumnIdentity>,
    /// A `GENERATED ALWAYS AS (...) STORED` column: can't be written.
    pub generated: bool,
    pub is_primary_key: bool,
    pub comment: Option<String>,
    pub foreign_keys: Vec<ForeignKeyRef>,
}

/// How rows of a table are told apart when editing (ANG-8 D2).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, specta::Type)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum RowIdentity {
    PrimaryKey {
        columns: Vec<String>,
    },
    /// A unique index whose columns are all NOT NULL.
    UniqueIndex {
        columns: Vec<String>,
    },
    /// No key: rows are found by `ctid`, which changes when a row is updated, so edits re-read
    /// the table afterwards.
    Ctid,
    /// Rows can't be edited; `reason` is shown to the user.
    ReadOnly {
        reason: String,
    },
}

#[derive(Debug, Clone, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct TableDescription {
    pub schema: String,
    pub name: String,
    pub kind: ObjectKind,
    pub comment: Option<String>,
    pub columns: Vec<ColumnInfo>,
    pub identity: RowIdentity,
}
