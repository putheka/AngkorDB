#[cfg(test)]
mod tests {
    use super::*;

    fn column(name: &str, type_name: &str) -> NewTableColumn {
        NewTableColumn {
            name: name.into(),
            type_name: type_name.into(),
            nullable: true,
            default_value: None,
            identity: None,
            primary_key: false,
            comment: None,
        }
    }

    fn sql(operation: ObjectOperation) -> Vec<String> {
        plan(&operation)
            .unwrap()
            .into_iter()
            .map(|s| s.sql)
            .collect()
    }

    #[test]
    fn a_table_with_an_identity_key_defaults_and_comments() {
        let out = sql(ObjectOperation::CreateTable(CreateTable {
            schema: "public".into(),
            name: "events".into(),
            comment: Some("What happened".into()),
            columns: vec![
                NewTableColumn {
                    identity: Some(ColumnIdentity::Always),
                    primary_key: true,
                    nullable: false,
                    ..column("id", "bigint")
                },
                NewTableColumn {
                    nullable: false,
                    comment: Some("Who's there".into()),
                    ..column("name", "text")
                },
                NewTableColumn {
                    nullable: false,
                    default_value: Some("now()".into()),
                    ..column("created_at", "timestamp with time zone")
                },
                NewTableColumn {
                    identity: Some(ColumnIdentity::ByDefault),
                    ..column("seq", "integer")
                },
            ],
        }));
        assert_eq!(
            out,
            [
                "CREATE TABLE \"public\".\"events\" (\n    \"id\" bigint GENERATED ALWAYS AS IDENTITY NOT NULL,\n    \"name\" text NOT NULL,\n    \"created_at\" timestamp with time zone DEFAULT now() NOT NULL,\n    \"seq\" integer GENERATED BY DEFAULT AS IDENTITY,\n    PRIMARY KEY (\"id\")\n);",
                "COMMENT ON TABLE \"public\".\"events\" IS 'What happened';",
                "COMMENT ON COLUMN \"public\".\"events\".\"name\" IS 'Who''s there';",
            ]
        );
    }

    #[test]
    fn a_composite_key_lists_its_columns_in_order() {
        let out = sql(ObjectOperation::CreateTable(CreateTable {
            schema: "s".into(),
            name: "t".into(),
            comment: None,
            columns: vec![
                NewTableColumn {
                    primary_key: true,
                    ..column("a", "integer")
                },
                column("b", "text"),
                NewTableColumn {
                    primary_key: true,
                    ..column("c", "integer")
                },
            ],
        }));
        assert!(out[0].contains("PRIMARY KEY (\"a\", \"c\")"), "{}", out[0]);
    }

    #[test]
    fn mistakes_in_a_new_table_are_refused() {
        let table = |columns: Vec<NewTableColumn>, name: &str| {
            plan(&ObjectOperation::CreateTable(CreateTable {
                schema: "public".into(),
                name: name.into(),
                comment: None,
                columns,
            }))
        };
        assert!(table(vec![], "t").is_err(), "no columns");
        assert!(table(vec![column("a", "text")], "  ").is_err(), "no name");
        assert!(
            table(vec![column(" ", "text")], "t").is_err(),
            "a column has no name"
        );
        assert!(
            table(vec![column("a", "text"), column("a", "integer")], "t").is_err(),
            "two columns with one name"
        );
        assert!(
            table(vec![column("a", "text; DROP TABLE x")], "t").is_err(),
            "bad type"
        );
        assert!(
            table(
                vec![NewTableColumn {
                    identity: Some(ColumnIdentity::Always),
                    ..column("a", "text")
                }],
                "t"
            )
            .is_err(),
            "identity on text"
        );
        assert!(
            table(
                vec![NewTableColumn {
                    identity: Some(ColumnIdentity::Always),
                    default_value: Some("1".into()),
                    ..column("a", "integer")
                }],
                "t"
            )
            .is_err(),
            "identity with a default"
        );
        assert!(
            table(
                vec![NewTableColumn {
                    default_value: Some("1; DROP TABLE x".into()),
                    ..column("a", "integer")
                }],
                "t"
            )
            .is_err(),
            "default with a second statement"
        );
    }

    #[test]
    fn rename_truncate_and_drop() {
        let rename = |kind, new: &str| {
            sql(ObjectOperation::Rename(RenameObject {
                object_kind: kind,
                schema: "public".into(),
                name: "old".into(),
                new_name: new.into(),
            }))
        };
        assert_eq!(
            rename(ObjectKind::Table, "new"),
            ["ALTER TABLE \"public\".\"old\" RENAME TO \"new\";"]
        );
        assert_eq!(
            rename(ObjectKind::View, "We\"ird"),
            ["ALTER VIEW \"public\".\"old\" RENAME TO \"We\"\"ird\";"]
        );
        assert_eq!(
            rename(ObjectKind::MaterializedView, "m"),
            ["ALTER MATERIALIZED VIEW \"public\".\"old\" RENAME TO \"m\";"]
        );

        let truncate = |restart, cascade| {
            plan(&ObjectOperation::Truncate(TruncateTable {
                schema: "public".into(),
                name: "t".into(),
                restart_identity: restart,
                cascade,
            }))
            .unwrap()
        };
        assert_eq!(
            truncate(false, false)[0].sql,
            "TRUNCATE TABLE \"public\".\"t\";"
        );
        assert_eq!(
            truncate(true, true)[0].sql,
            "TRUNCATE TABLE \"public\".\"t\" RESTART IDENTITY CASCADE;"
        );
        assert!(truncate(false, false)[0].destructive);

        let drop = |kind, cascade| {
            plan(&ObjectOperation::Drop(DropObject {
                object_kind: kind,
                schema: "public".into(),
                name: "x".into(),
                cascade,
            }))
            .unwrap()
        };
        assert_eq!(
            drop(ObjectKind::Table, false)[0].sql,
            "DROP TABLE \"public\".\"x\";"
        );
        assert_eq!(
            drop(ObjectKind::View, true)[0].sql,
            "DROP VIEW \"public\".\"x\" CASCADE;"
        );
        assert!(drop(ObjectKind::MaterializedView, false)[0].destructive);
    }

    #[test]
    fn only_tables_and_views_and_real_changes() {
        for kind in [
            ObjectKind::Sequence,
            ObjectKind::Function,
            ObjectKind::EnumType,
        ] {
            assert!(
                plan(&ObjectOperation::Drop(DropObject {
                    object_kind: kind,
                    schema: "public".into(),
                    name: "x".into(),
                    cascade: false,
                }))
                .is_err(),
                "{kind:?}"
            );
        }
        let same = plan(&ObjectOperation::Rename(RenameObject {
            object_kind: ObjectKind::Table,
            schema: "public".into(),
            name: "a".into(),
            new_name: "a".into(),
        }));
        assert!(same.is_err());
        let blank = plan(&ObjectOperation::Rename(RenameObject {
            object_kind: ObjectKind::Table,
            schema: "public".into(),
            name: "a".into(),
            new_name: " ".into(),
        }));
        assert!(blank.is_err());
    }

    #[test]
    fn the_preview_says_it_is_one_transaction() {
        let p = preview(&ObjectOperation::Truncate(TruncateTable {
            schema: "public".into(),
            name: "t".into(),
            restart_identity: false,
            cascade: false,
        }))
        .unwrap();
        assert!(p.sql.starts_with("-- In one transaction"), "{}", p.sql);
        assert!(p.sql.ends_with("TRUNCATE TABLE \"public\".\"t\";"));
    }
}
