//! Create, rename, truncate and drop tables and views (ANG-38).
//!
//! Same shape as [`crate::db::alter`]: [`plan`] writes the statements (names quoted, anything
//! typed checked to be one piece of SQL), [`preview`] shows them, [`apply`] runs them in one
//! transaction with a lock timeout.

use std::collections::HashSet;

use tokio_postgres::Client;

use crate::db::alter::{LOCK_TIMEOUT_MS, check_fragment, check_type};
use crate::db::rows::quote_ident;
use crate::db::script;
use crate::db::structure::literal;
use crate::error::{AppError, AppResult};
use crate::models::alter::{PlannedStatement, StructurePreview};
use crate::models::objects::{
    CreateTable, DropObject, NewTableColumn, ObjectOperation, RenameObject, TruncateTable,
};
use crate::models::schema::{ColumnIdentity, ObjectKind};

fn invalid(message: impl Into<String>) -> AppError {
    AppError::Validation(message.into())
}

fn relation(schema: &str, name: &str) -> AppResult<String> {
    if schema.trim().is_empty() || name.trim().is_empty() {
        return Err(invalid("Which table?"));
    }
    Ok(format!("{}.{}", quote_ident(schema), quote_ident(name)))
}

/// `TABLE`, `VIEW`, … as the statement says it; only what can be renamed and dropped here.
fn keyword(kind: ObjectKind) -> AppResult<&'static str> {
    match kind {
        ObjectKind::Table | ObjectKind::PartitionedTable => Ok("TABLE"),
        ObjectKind::ForeignTable => Ok("FOREIGN TABLE"),
        ObjectKind::View => Ok("VIEW"),
        ObjectKind::MaterializedView => Ok("MATERIALIZED VIEW"),
        _ => Err(invalid("Only tables and views can be changed here.")),
    }
}

fn describe(kind: ObjectKind) -> &'static str {
    match kind {
        ObjectKind::View => "view",
        ObjectKind::MaterializedView => "materialized view",
        ObjectKind::ForeignTable => "foreign table",
        _ => "table",
    }
}

fn statement(label: impl Into<String>, sql: String, destructive: bool) -> PlannedStatement {
    PlannedStatement {
        sql,
        label: label.into(),
        change: 1,
        concurrent: false,
        destructive,
    }
}

const INTEGER_TYPES: [&str; 6] = ["smallint", "integer", "bigint", "int", "int2", "int4"];

fn is_integer_type(type_name: &str) -> bool {
    let lower = type_name.trim().to_ascii_lowercase();
    lower == "int8" || INTEGER_TYPES.contains(&lower.as_str())
}

fn column_line(column: &NewTableColumn) -> AppResult<String> {
    if column.name.trim().is_empty() {
        return Err(invalid("A column has no name."));
    }
    check_type(&column.type_name)?;
    let mut line = format!("{} {}", quote_ident(&column.name), column.type_name.trim());
    let default = column
        .default_value
        .as_deref()
        .filter(|d| !d.trim().is_empty());
    match (column.identity, default) {
        (Some(_), Some(_)) => {
            return Err(invalid(format!(
                "Column {}: an identity column can't also have a default.",
                column.name
            )));
        }
        (Some(identity), None) => {
            if !is_integer_type(&column.type_name) {
                return Err(invalid(format!(
                    "Column {}: only smallint, integer and bigint can be an identity.",
                    column.name
                )));
            }
            line.push_str(match identity {
                ColumnIdentity::Always => " GENERATED ALWAYS AS IDENTITY",
                ColumnIdentity::ByDefault => " GENERATED BY DEFAULT AS IDENTITY",
            });
        }
        (None, Some(default)) => {
            check_fragment(default, &format!("The default of {}", column.name))?;
            line.push_str(&format!(" DEFAULT {}", default.trim()));
        }
        (None, None) => {}
    }
    if !column.nullable {
        line.push_str(" NOT NULL");
    }
    Ok(line)
}

fn create_table(c: &CreateTable, out: &mut Vec<PlannedStatement>) -> AppResult<()> {
    if c.name.trim().is_empty() {
        return Err(invalid("Give the table a name."));
    }
    if c.columns.is_empty() {
        return Err(invalid("A table needs at least one column."));
    }
    let table = relation(&c.schema, &c.name)?;

    let mut seen = HashSet::new();
    for column in &c.columns {
        if !seen.insert(column.name.as_str()) {
            return Err(invalid(format!(
                "Two columns are called \"{}\".",
                column.name
            )));
        }
    }
    let mut lines = c
        .columns
        .iter()
        .map(|column| column_line(column).map(|line| format!("    {line}")))
        .collect::<AppResult<Vec<_>>>()?;
    let key: Vec<String> = c
        .columns
        .iter()
        .filter(|column| column.primary_key)
        .map(|column| quote_ident(&column.name))
        .collect();
    if !key.is_empty() {
        lines.push(format!("    PRIMARY KEY ({})", key.join(", ")));
    }
    out.push(statement(
        format!("create table {}", c.name),
        format!("CREATE TABLE {table} (\n{}\n);", lines.join(",\n")),
        false,
    ));

    if let Some(comment) = c.comment.as_deref().filter(|t| !t.is_empty()) {
        out.push(statement(
            format!("comment on table {}", c.name),
            format!("COMMENT ON TABLE {table} IS {};", literal(comment)),
            false,
        ));
    }
    for column in &c.columns {
        if let Some(comment) = column.comment.as_deref().filter(|t| !t.is_empty()) {
            out.push(statement(
                format!("comment on column {}", column.name),
                format!(
                    "COMMENT ON COLUMN {table}.{} IS {};",
                    quote_ident(&column.name),
                    literal(comment)
                ),
                false,
            ));
        }
    }
    Ok(())
}

fn rename(r: &RenameObject, out: &mut Vec<PlannedStatement>) -> AppResult<()> {
    let what = keyword(r.object_kind)?;
    if r.new_name.trim().is_empty() {
        return Err(invalid("Give it a new name."));
    }
    if r.new_name == r.name {
        return Err(invalid("That is the name it has already."));
    }
    out.push(statement(
        format!(
            "rename {} {} to {}",
            describe(r.object_kind),
            r.name,
            r.new_name
        ),
        format!(
            "ALTER {what} {} RENAME TO {};",
            relation(&r.schema, &r.name)?,
            quote_ident(&r.new_name)
        ),
        false,
    ));
    Ok(())
}

fn truncate(t: &TruncateTable, out: &mut Vec<PlannedStatement>) -> AppResult<()> {
    let mut sql = format!("TRUNCATE TABLE {}", relation(&t.schema, &t.name)?);
    if t.restart_identity {
        sql.push_str(" RESTART IDENTITY");
    }
    if t.cascade {
        sql.push_str(" CASCADE");
    }
    sql.push(';');
    out.push(statement(format!("truncate table {}", t.name), sql, true));
    Ok(())
}

fn drop_object(d: &DropObject, out: &mut Vec<PlannedStatement>) -> AppResult<()> {
    let what = keyword(d.object_kind)?;
    let cascade = if d.cascade { " CASCADE" } else { "" };
    out.push(statement(
        format!("drop {} {}", describe(d.object_kind), d.name),
        format!("DROP {what} {}{cascade};", relation(&d.schema, &d.name)?),
        true,
    ));
    Ok(())
}

/// The statements for an operation.
pub fn plan(operation: &ObjectOperation) -> AppResult<Vec<PlannedStatement>> {
    let mut out = Vec::new();
    match operation {
        ObjectOperation::CreateTable(c) => create_table(c, &mut out)?,
        ObjectOperation::Rename(r) => rename(r, &mut out)?,
        ObjectOperation::Truncate(t) => truncate(t, &mut out)?,
        ObjectOperation::Drop(d) => drop_object(d, &mut out)?,
    }
    for statement in &out {
        if script::split(&statement.sql).len() != 1 {
            return Err(invalid("That would run as more than one statement."));
        }
    }
    Ok(out)
}

pub fn preview(operation: &ObjectOperation) -> AppResult<StructurePreview> {
    let statements = plan(operation)?;
    let sql = format!(
        "-- In one transaction: all or nothing.\n{}",
        statements
            .iter()
            .map(|s| s.sql.as_str())
            .collect::<Vec<_>>()
            .join("\n")
    );
    Ok(StructurePreview { statements, sql })
}

/// Run the operation in one transaction. Returns how many statements ran.
pub async fn apply(
    client: &Client,
    operation: &ObjectOperation,
    lock_timeout_ms: u32,
) -> AppResult<u32> {
    let statements = plan(operation)?;
    client
        .batch_execute(&format!(
            "BEGIN; SET LOCAL lock_timeout = {lock_timeout_ms}"
        ))
        .await?;
    for statement in &statements {
        if let Err(e) = client.batch_execute(&statement.sql).await {
            // An aborted transaction must not go back to the pool.
            let _ = client.batch_execute("ROLLBACK").await;
            return Err(e.into());
        }
    }
    if let Err(e) = client.batch_execute("COMMIT").await {
        let _ = client.batch_execute("ROLLBACK").await;
        return Err(e.into());
    }
    Ok(u32::try_from(statements.len()).unwrap_or(u32::MAX))
}

