/** A plan as a plain EXPLAIN prints it: what only ANALYZE adds is taken out. */
export function planWithoutActuals(plan: unknown): unknown {
  const text = JSON.stringify(plan, (key, value: unknown) =>
    /^(Actual |Shared |Local |Temp |Workers Launched|Rows Removed|Heap Fetches|Sort Method|Sort Space)/.test(
      key,
    ) ||
    key === "Execution Time" ||
    key === "Workers"
      ? undefined
      : value,
  );
  return JSON.parse(text) as unknown;
}
