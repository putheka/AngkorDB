/** Preview and apply for create / rename / truncate / drop in the in-browser mock. */
import type {
  ObjectDefinition,
  ObjectOperation,
  PlannedStatement,
  SequenceInfo,
  StructurePreview,
} from "@/bindings";
import {
  mockAddEnumValue,
  mockCreateTable,
  mockDropObject,
  mockEnumValues,
  mockHasObject,
  mockRenameObject,
  mockSequence,
  mockSetSequence,
} from "@/dev/mockSchema";
import { appError } from "@/dev/mockSupport";

const q = (name: string) => `"${name.replace(/"/g, '""')}"`;
const WORDS = {
  table: "TABLE",
  partitionedTable: "TABLE",
  foreignTable: "FOREIGN TABLE",
  view: "VIEW",
  materializedView: "MATERIALIZED VIEW",
} as const;

function statements(op: ObjectOperation): PlannedStatement[] {
  const one = (label: string, sql: string, destructive = false): PlannedStatement[] => [
    { sql, label, change: 1, concurrent: false, destructive },
  ];
  switch (op.kind) {
    case "createTable": {
      if (op.name.trim() === "") throw appError("VALIDATION", "Give the table a name.");
      if (op.columns.length === 0)
        throw appError("VALIDATION", "A table needs at least one column.");
      const lines = op.columns.map(
        (c) =>
          `    ${q(c.name)} ${c.typeName}${c.identity === "always" ? " GENERATED ALWAYS AS IDENTITY" : c.identity === "byDefault" ? " GENERATED BY DEFAULT AS IDENTITY" : c.defaultValue ? ` DEFAULT ${c.defaultValue}` : ""}${c.nullable ? "" : " NOT NULL"}`,
      );
      const key = op.columns.filter((c) => c.primaryKey).map((c) => q(c.name));
      if (key.length > 0) lines.push(`    PRIMARY KEY (${key.join(", ")})`);
      const table = `${q(op.schema)}.${q(op.name)}`;
      const out = one(
        `create table ${op.name}`,
        `CREATE TABLE ${table} (\n${lines.join(",\n")}\n);`,
      );
      if (op.comment) {
        out.push({
          sql: `COMMENT ON TABLE ${table} IS '${op.comment.replace(/'/g, "''")}';`,
          label: `comment on table ${op.name}`,
          change: 1,
          concurrent: false,
          destructive: false,
        });
      }
      return out;
    }
    case "rename":
      return one(
        `rename ${op.name} to ${op.newName}`,
        `ALTER ${WORDS[op.objectKind as keyof typeof WORDS] ?? "TABLE"} ${q(op.schema)}.${q(op.name)} RENAME TO ${q(op.newName)};`,
      );
    case "truncate":
      return one(
        `truncate table ${op.name}`,
        `TRUNCATE TABLE ${q(op.schema)}.${q(op.name)}${op.restartIdentity ? " RESTART IDENTITY" : ""}${op.cascade ? " CASCADE" : ""};`,
        true,
      );
    case "refreshMaterializedView":
      if (op.concurrently && op.withNoData) {
        throw appError("VALIDATION", "CONCURRENTLY and WITH NO DATA can't be used together.");
      }
      return one(
        `refresh materialized view ${op.name}`,
        `REFRESH MATERIALIZED VIEW ${op.concurrently ? "CONCURRENTLY " : ""}${q(op.schema)}.${q(op.name)}${op.withNoData ? " WITH NO DATA" : ""};`,
      );
    case "setSequence":
      if (!/^-?\d+$/.test(op.value.trim())) {
        throw appError("VALIDATION", "The value has to be a whole number.");
      }
      return one(
        `set sequence ${op.name}`,
        `SELECT setval('${q(op.schema)}.${q(op.name)}'::regclass, ${op.value.trim()}, ${op.isCalled});`,
      );
    case "addEnumValue":
      if (op.value === "") throw appError("VALIDATION", "The new value is empty.");
      return one(
        `add value to ${op.name}`,
        `ALTER TYPE ${q(op.schema)}.${q(op.name)} ADD VALUE ${op.ifNotExists ? "IF NOT EXISTS " : ""}'${op.value.replace(/'/g, "''")}'${op.position ? ` ${op.position.before ? "BEFORE" : "AFTER"} '${op.position.existing}'` : ""};`,
      );
    case "drop":
      return one(
        `drop ${op.name}`,
        `DROP ${WORDS[op.objectKind as keyof typeof WORDS] ?? "TABLE"} ${q(op.schema)}.${q(op.name)}${op.cascade ? " CASCADE" : ""};`,
        true,
      );
  }
}

export function mockObjectPreview(op: ObjectOperation): StructurePreview {
  if (op.kind === "rename" && op.newName.trim() === "") {
    throw appError("VALIDATION", "Give it a new name.");
  }
  const list = statements(op);
  return {
    statements: list,
    sql: `-- In one transaction: all or nothing.\n${list.map((s) => s.sql).join("\n")}`,
  };
}

export function mockObjectApply(op: ObjectOperation): number {
  const count = mockObjectPreview(op).statements.length;
  switch (op.kind) {
    case "createTable":
      mockCreateTable(op.schema, op.name, op.columns);
      break;
    case "rename":
      mockRenameObject(op.schema, op.name, op.newName);
      break;
    case "drop":
      mockDropObject(op.schema, op.name);
      break;
    case "refreshMaterializedView":
      break;
    case "setSequence":
      mockSetSequence(op.schema, op.name, op.value.trim(), op.isCalled);
      break;
    case "addEnumValue":
      mockAddEnumValue(op.value, op.position, op.ifNotExists);
      break;
    case "truncate":
      if (!mockHasObject(op.schema, op.name)) {
        throw appError("POSTGRES", `relation "${op.name}" does not exist`, { pgCode: "42P01" });
      }
      break;
  }
  return count;
}

/** The text a function, view, enum or sequence would show, close to what PostgreSQL writes. */
export function mockDefinition(kind: string, schema: string, name: string): ObjectDefinition {
  const target = `${schema}.${name}`;
  switch (kind) {
    case "function":
      return {
        title: `${name}()`,
        sql: `CREATE OR REPLACE FUNCTION ${target}(p_name text DEFAULT 'world'::text)\n RETURNS text\n LANGUAGE plpgsql\nAS $function$\nDECLARE\n  msg text := 'Hello; ' || p_name || '! -- not a comment';\nBEGIN\n  RETURN msg || ' /* not a comment either */';\nEND;\n$function$;\n`,
      };
    case "view":
      return {
        title: name,
        sql: `CREATE OR REPLACE VIEW ${target} AS\nSELECT u.id AS user_id,\n    u.email\n   FROM public.users u;\n`,
      };
    case "materializedView":
      return {
        title: name,
        sql: `-- A materialized view can't be replaced in place: to change it, drop it and make it\n-- again. Dropping it also drops its indexes; they are made again below.\nDROP MATERIALIZED VIEW ${target};\nCREATE MATERIALIZED VIEW ${target} AS\nSELECT 1 AS n\nWITH DATA;\n`,
      };
    case "enumType":
      return {
        title: name,
        sql: `CREATE TYPE ${target} AS ENUM (${mockEnumValues()
          .map((v) => `'${v}'`)
          .join(", ")});\n`,
      };
    default:
      throw appError("VALIDATION", "Tables have their DDL in the Structure view.");
  }
}

export function mockSequenceInfo(schema: string, name: string): SequenceInfo {
  const state = mockSequence(schema, name);
  return {
    dataType: "bigint",
    start: schema === "billing" ? "1000" : "1",
    increment: "1",
    min: "1",
    max: "9223372036854775807",
    cache: "1",
    cycle: false,
    lastValue: state.called ? state.last : null,
    ownedBy: schema === "public" ? "public.orders.id" : null,
  };
}
